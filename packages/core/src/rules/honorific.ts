import type { Warning } from '../contract';

type HonorificLevel = 'hapsyo' | 'haeyo';

/**
 * 🔴 reviewer Major 2 스팟체크 케이스 3(`자료를 첨부했습니다(v2). 확인해 주세요.`) — 종결어미와
 * 마침표 사이에 괄호 부기("(v2)" 등)가 끼면 원래는 앵커(`$`)가 어긋나 미검출이었다. 종결어미 뒤에
 * "(...)" 형태의 괄호 부기 1개를 선택적으로 허용해 고쳤다.
 */
const TRAILING_PARENTHETICAL = /(?:\([^)]*\))?/.source;

/** 합쇼체 종결어미 — "-습니다/-습니까/-ㅂ니다(합니다·갑니다 등)/-십시오". */
const HAPSYO_ENDING = new RegExp(`(니다|니까|십시오)${TRAILING_PARENTHETICAL}[.!?]?$`);

/** 해요체 종결어미 — "-아요/-어요/-여요/-예요/-이에요/-네요/-죠" 등, 표층상 공통적으로 "요"/"죠"로 끝난다. */
const HAEYO_ENDING = new RegExp(`(요|죠)${TRAILING_PARENTHETICAL}[.!?]?$`);

function classifySentence(sentence: string): HonorificLevel | null {
  const trimmed = sentence.trim();
  if (trimmed === '') return null;
  if (HAPSYO_ENDING.test(trimmed)) return 'hapsyo';
  if (HAEYO_ENDING.test(trimmed)) return 'haeyo';
  return null;
}

/**
 * 텍스트를 문장 단위로 나눈다 — 마침표/느낌표/물음표 뒤(공백 유무 무관), 합쇼체 종결어미 뒤
 * 공백, 또는 줄바꿈 기준.
 * 🔴 reviewer Major 2 스팟체크 케이스 2(`확인 부탁드립니다.편하실 때 연락 주세요.`) — 마침표
 * 뒤에 공백이 없으면 원래 나뉘지 않아 두 문장이 하나로 합쳐져 미검출이었다. `\s+`를 `\s*`로
 * 바꿔 공백이 없어도 마침표/느낌표/물음표 직후에서 나뉘게 했다.
 * 🔴 reviewer 5차 Critical(수정) 스팟체크 케이스 1·4 — 구두점이 아예 없거나(케이스 1) 구두점
 * 없는 절 경계를 이모지가 대신하는 경우(케이스 4)는 마침표 기준만으로는 나뉘지 않았다. 합쇼체
 * 종결어미(니다/니까/십시오) 바로 뒤에 공백이 오면 그 자리도 문장 경계로 본다 — "습니다만"처럼
 * 종결어미 뒤에 조사/어미가 곧장(공백 없이) 이어지는 경우는 매치되지 않으므로 안전하다.
 * 🔴 QA 6차 Critical(수정) — 이 분리를 도입한 대가로 새 오탐 계열이 생긴다: 갈라진 뒤 조각이
 * 명사+"요"(필요/중요/주요 등)로 끝나면 해요체로 오분류된다. 파일 헤더 주석의 known gap
 * 케이스 5~10 참조.
 */
const SENTENCE_BOUNDARY = /(?<=[.!?])\s*|(?<=(?:니다|니까|십시오))\s+|\n+/;

function splitSentences(text: string): string[] {
  return text
    .split(SENTENCE_BOUNDARY)
    .map((sentence) => sentence.trim())
    .filter((sentence) => sentence.length > 0);
}

/**
 * 한 메시지 안에 합쇼체/해요체가 섞였는지 판정한다(AC-046①③).
 * 🔴 분류되지 않는 문장(명사구·인사말 등)은 판정에서 제외한다 — "판정 불가"를 "혼용"으로
 * 오판하지 않는다(둘 이상의 서로 다른 레벨이 실제로 검출된 경우만 혼용).
 */
export function detectHonorificMixing(text: string): boolean {
  const levels = new Set<HonorificLevel>();
  for (const sentence of splitSentences(text)) {
    const level = classifySentence(sentence);
    if (level) levels.add(level);
  }
  return levels.size > 1;
}

/**
 * 혼용이 감지되면 `warnings[]`에 넣을 `Warning`을 만든다(AC-046③). 감지되지 않으면 `null`
 * — "경고가 없으면 아무것도 표시하지 않는다"(`docs/Tasks.md` T6)를 호출부가 그대로 반영할 수 있게 한다.
 * 🔴 문구에 국가·국민성 서술을 넣지 않는다(`docs/Architecture.md` Conventions 7 — 언어쌍(KO↔EN)
 * 규칙으로만 적용, 국민성 서술 금지).
 */
export function honorificMixedWarning(text: string): Warning | null {
  if (!detectHonorificMixing(text)) return null;
  return {
    type: 'honorificLevelMixed',
    message: '한 메시지 안에 존댓말 레벨(합쇼체/해요체)이 섞여 있습니다.',
    subject: null,
  };
}
